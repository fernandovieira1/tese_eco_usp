import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const [input,output,preview]=process.argv.slice(2);
const wb=Workbook.create();
const s=wb.worksheets.add('Catalogo');
const exact=JSON.parse(await fs.readFile(input.replace(/\.csv$/,'.values.json'),'utf8'));
s.getRangeByIndexes(0,0,exact.length,exact[0].length).values=exact;
const range=s.getUsedRange();
range.format.font={name:'Arial',size:10};
range.format.wrapText=true;
range.format.verticalAlignment='top';
range.format.columnWidth=25;
s.getRange('A:A').format.columnWidth=42;
s.getRange('B:B').format.columnWidth=68;
s.getRange('D:D').format.columnWidth=68;
s.getRange('L:L').format.columnWidth=74;
s.getRange('S:S').format.columnWidth=68;
range.format.autofitRows();
s.getRange('A1:S1').format={fill:'#243746',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},wrapText:true,rowHeight:45};
s.freezePanes.freezeRows(1);s.freezePanes.freezeColumns(1);s.showGridLines=false;
s.tables.add(range.address??`A1:S${range.values.length}`,true,'CatalogoDados');
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Catalogo!A1:F4',include:'values',tableMaxRows:4,tableMaxCols:6,maxChars:1800})).ndjson);
const out=await SpreadsheetFile.exportXlsx(wb);await out.save(output);
const image=await wb.render({sheetName:'Catalogo',range:'A1:C5',scale:1,format:'png'});
await fs.writeFile(preview,new Uint8Array(await image.arrayBuffer()));
console.log('EXPORTED',output);
